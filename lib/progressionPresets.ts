export function progressionPresetRomanLabel(preset: ProgressionPreset) {
  return preset.roman.join(" - ");
}

export function progressionPresetToChords(
  preset: ProgressionPreset,
  params: { key: string; mode: KeyMode }
) {
  const cacheKey = `${preset.id}|${params.key}|${params.mode}|${preset.roman.join(" ")}`;
  const cached = presetChordCache.get(cacheKey);
  if (cached) return cached;

  const chords = preset.roman.map((roman) => romanCandidateToChord(roman, params));
  presetChordCache.set(cacheKey, chords);
  if (presetChordCache.size > PRESET_CHORD_CACHE_LIMIT) {
    const oldest = presetChordCache.keys().next().value;
    if (oldest !== undefined) presetChordCache.delete(oldest);
  }
  return chords;
}

function selectedValue(value?: string) {
  return value && value !== "All" ? value.toLowerCase() : "";
}

function includesSelected(values: string[], selected?: string) {
  const normalized = selectedValue(selected);
  if (!normalized) return true;
  return values.some((value) => value.toLowerCase() === normalized);
}

export function filterProgressionPresets(
  presets: ProgressionPreset[],
  filter: PresetFilter,
  options: {
    convertedChords?: (preset: ProgressionPreset) => string[];
  } = {}
) {
  const category = selectedValue(filter.category);
  const complexity =
    filter.complexity && filter.complexity !== "All"
      ? Number(filter.complexity)
      : 0;
  const query = filter.search?.trim().toLowerCase() ?? "";

  return presets.filter((preset) => {
    if (category && preset.category.toLowerCase() !== category) return false;
    if (!includesSelected(preset.genres, filter.genre)) return false;
    if (!includesSelected(preset.moods, filter.mood)) return false;
    if (!includesSelected(preset.useCases, filter.useCase)) return false;
    if (complexity && preset.complexity !== complexity) return false;
    if (!query) return true;

    const references =
      preset.referenceSongs?.flatMap((ref) => [
        ref.title,
        ref.artist ?? "",
        ref.section ?? "",
        ref.note ?? "",
      ]) ?? [];
    const convertedChords = options.convertedChords?.(preset) ?? [];
    const haystack = [
      preset.name,
      progressionPresetRomanLabel(preset),
      convertedChords.join(" "),
      preset.description,
      preset.commonUse ?? "",
      preset.mode,
      preset.category,
      ...preset.genres,
      ...preset.moods,
      ...preset.useCases,
      ...(preset.vibeExamples ?? []),
      ...references,
    ]
      .join(" ")
      .toLowerCase();
    return haystack.includes(query);
  });
}
