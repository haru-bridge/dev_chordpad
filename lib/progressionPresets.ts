export type PresetMode = "major" | "minor" | "either";

export type ProgressionPresetCategory =
  | "I-start"
  | "IV-start"
  | "vi-start"
  | "minor"
  | "ii-V"
  | "turnaround"
  | "modal"
  | "borrowed"
  | "other";

export type ProgressionUseCase =
  | "intro"
  | "verse"
  | "pre-chorus"
  | "chorus"
  | "bridge"
  | "ending"
  | "loop"
  | "turnaround"
  | "drop";

export type ReferenceSong = {
  title: string;
  artist?: string;
  section?:
    | "intro"
    | "verse"
    | "pre-chorus"
    | "chorus"
    | "bridge"
    | "outro"
    | "unknown";
  confidence: "high" | "medium" | "low";
  note?: string;
};

export type ProgressionPreset = {
  id: string;
  name: string;
  roman: string[];
  mode: PresetMode;
  category: ProgressionPresetCategory;
  genres: string[];
  moods: string[];
  useCases: ProgressionUseCase[];
  complexity: 1 | 2 | 3 | 4 | 5;
  description: string;
  vibeExamples?: string[];
  referenceSongs?: ReferenceSong[];
  commonUse?: string;
  variationHints?: string[];
};

